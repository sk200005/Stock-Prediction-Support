from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware

from backend.models.article import (
    ArticlesResponse,
    CompanyMentionsResponse,
    CompanySignalsResponse,
)
from backend.models.stats import (
    ImpactDistributionResponse,
    PipelineRunResponse,
    StatsResponse,
)
from backend.routes.market_insights import router as market_insights_router
from backend.routes.sentiment_analytics import router as sentiment_analytics_router
from backend.services.analytics import (
    compute_company_signals,
    compute_impact_distribution,
    compute_mentions,
    compute_stats,
)
from backend.services.data_loader import load_articles
from backend.services.mongo_client import mongo_is_available
from backend.services.pipeline import run_news_pipeline


app = FastAPI(
    title="Financial News Market Signal API",
    description="Read-only API over processed market signal data generated by the NLP pipeline.",
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173", "http://127.0.0.1:5173"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(market_insights_router)
app.include_router(sentiment_analytics_router)


@app.get("/health")
def health_check() -> dict:
    return {
        "status": "ok",
        "mongo_available": mongo_is_available(),
    }


@app.get("/articles", response_model=ArticlesResponse)
def get_articles() -> ArticlesResponse:
    articles = load_articles()
    return ArticlesResponse(articles=articles)


@app.get("/stats", response_model=StatsResponse)
def get_stats() -> StatsResponse:
    articles = load_articles()
    return StatsResponse(**compute_stats(articles))


@app.get("/company-signals", response_model=CompanySignalsResponse)
def get_company_signals() -> CompanySignalsResponse:
    articles = load_articles()
    return CompanySignalsResponse(
        company_signals=compute_company_signals(articles)
    )


@app.get("/mentions", response_model=CompanyMentionsResponse)
def get_mentions() -> CompanyMentionsResponse:
    articles = load_articles()
    return CompanyMentionsResponse(mentions=compute_mentions(articles))


@app.get("/impact-distribution", response_model=ImpactDistributionResponse)
def get_impact_distribution() -> ImpactDistributionResponse:
    articles = load_articles()
    return ImpactDistributionResponse(**compute_impact_distribution(articles))


@app.post("/run-pipeline", response_model=PipelineRunResponse)
def trigger_pipeline() -> PipelineRunResponse:
    try:
        result = run_news_pipeline()
        return PipelineRunResponse(**result)
    except RuntimeError as error:
        raise HTTPException(status_code=500, detail=str(error)) from error
